"""Generate db/pg/94_deployment_profile.sql from the two text exports of the compared deployment's configuration tables.

The rebuild is compared against one running deployment of the original (FazalDinPP19): which columns each window shows is not in the program but in the
configuration tables InterfaceSetting / SaleInterface, and many screens depend on the flag preferences (SoftwarePreferences).  Only configuration is taken:
no customer, supplier, item, account or user rows, and no preference that can hold a secret (passwords, keys, URLs, hosts, paths, licence data).

usage (local only, the SQL Server of the deployment is not available in CI):
  sqlcmd -S .\\SQLEXPRESS2022 -E -C -d <db> -W -h -1 -s "|" -Q "SET NOCOUNT ON; SELECT moduleid, sequenceid, colname, colcaption, visibility, wintype, interfacegroup FROM InterfaceSetting ORDER BY moduleid, wintype, sequenceid" > ifs.txt
  sqlcmd ... -Q "SET NOCOUNT ON; SELECT prefid, name, prefdatatype, prefvalue, prefvalue2 FROM SoftwarePreferences ORDER BY prefid" > prefs.txt
  sqlcmd ... -Q "SET NOCOUNT ON; SELECT * FROM SaleInterface" > saleif.txt
  python -I tools/gen_deployment_profile.py ifs.txt prefs.txt saleif.txt db/pg/94_deployment_profile.sql
"""
import re
import sys


def rows(path, n):
    out = []
    for line in open(path, encoding='utf-8', errors='replace'):
        p = line.rstrip('\n').split('|')
        if len(p) >= n and p[0].strip().lstrip('-').isdigit():
            out.append([x.strip() for x in p])
    return out


def q(s):
    return "'" + s.replace("'", "''") + "'"


ifs = rows(sys.argv[1], 7)
prefs = rows(sys.argv[2], 5)
saleif = rows(sys.argv[3], 2)
out_path = sys.argv[4]

# preferences that can hold a secret or a machine-specific value are never copied
secret = re.compile(r'smtp|api|host|url|username|userid|licen|regid|serial|path|comport|password$|^.*key$|folder|dir$|ownerphone|terms?\d*$', re.I)
flag = re.compile(r'^[YNX]$|^\d{1,6}$|^-?\d{1,4}(\.\d{1,4})?$')

lines = [
    '-- Generated by tools/gen_deployment_profile.py from the configuration tables of the compared deployment of the original.',
    '-- Configuration only (window column layout, flag preferences): no customer / supplier / item / account / user rows, no secrets.',
    '-- Applied after the seed and before 95_bootstrap.sql (which has the last word on start-up behaviour) so the screens start the way the original shows them; every statement is idempotent.',
    '',
]
lines.append('-- InterfaceSetting: which columns each window shows (%d rows)' % len(ifs))
for mid, seq, col, cap, vis, wt, grp in ifs:
    lines.append(
        'INSERT INTO dbo.interfacesetting (moduleid, sequenceid, colname, colcaption, visibility, wintype, interfacegroup) VALUES (%s, %s, %s, %s, %s, %s, %s) '
        'ON CONFLICT (moduleid, colname, wintype) DO UPDATE SET sequenceid = EXCLUDED.sequenceid, colcaption = EXCLUDED.colcaption, visibility = EXCLUDED.visibility, interfacegroup = EXCLUDED.interfacegroup;'
        % (mid, seq, q(col), q(cap), vis, wt, grp or '0'))
lines.append('')
lines.append('-- SaleInterface (%d rows)' % len(saleif))
for code, name in saleif:
    lines.append('INSERT INTO dbo.saleinterface (interfacecode, name) VALUES (%s, %s) ON CONFLICT (interfacecode) DO NOTHING;' % (code, q(name)))
lines.append('')
n = 0
lines.append('-- flag / number preferences of the deployment')
for pid, name, typ, v1, v2 in prefs:
    if secret.search(name) and not (typ.upper() == 'CHAR' and v1 in ('Y', 'N')):
        continue
    if not flag.match(v1):
        continue
    n += 1
    lines.append('UPDATE dbo.softwarepreferences SET prefvalue = %s WHERE lower(name) = %s;' % (q(v1), q(name.lower())))
lines.append('')
open(out_path, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print('interfacesetting %d, saleinterface %d, preferences %d' % (len(ifs), len(saleif), n))
