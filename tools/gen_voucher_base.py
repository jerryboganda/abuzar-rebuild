"""Generate db/pg/93_voucher_base.sql: the voucher categories of the original (cash / bank payment and receipt, journal, opening balances ...) and which sub accounts each may use.

These are definitions the accounts windows and f_... checks expect on a new company database; nothing of customers, suppliers or users.  Also the category account row 0 of the chart.

usage (local only):
  sqlcmd ... -Q "SET NOCOUNT ON; SELECT 'V', VochCatCode, Name, ShortName, [Counter], Posted, SystemType, JournalVoucher, ISNULL(HeaderTreatment,'NULL'), ISNULL(DetailTreatment,'NULL'), InvoiceBased, ISNULL(CAST(InvoiceType AS varchar(10)),'NULL'), AutoPosting, VoucherOrder, UseForSMS FROM dbo.VocherCategory ORDER BY 2" > voch.txt
  sqlcmd ... -Q "SET NOCOUNT ON; SELECT 'D', VochCatCode, SubAccCode FROM dbo.VocherCategoryDetail ORDER BY 2,3" > vochd.txt
  python -I tools/gen_voucher_base.py voch.txt vochd.txt db/pg/93_voucher_base.sql
"""
import sys


def q(s):
    return "'" + s.replace("'", "''") + "'"


def lit(v, text):
    return 'NULL' if v == 'NULL' else (q(v) if text else v)


lines = ['-- Generated by tools/gen_voucher_base.py from the voucher categories of the compared deployment of the original.  Idempotent; applied after 93_chart_base.sql (the sub accounts).', '']
lines.append("INSERT INTO dbo.categoryaccounts (catacccode, mainacccode, name) VALUES (0, 1, 'FIXED ASSETS1') ON CONFLICT DO NOTHING;")
cols = 'vochcatcode, name, shortname, counter, posted, systemtype, journalvoucher, headertreatment, detailtreatment, invoicebased, invoicetype, autoposting, voucherorder, useforsms'
for line in open(sys.argv[1], encoding='utf-8', errors='replace'):
    p = [x.strip() for x in line.rstrip('\n').split('|')]
    if len(p) < 15 or p[0] != 'V':
        continue
    _, code, name, short, counter, posted, systype, jv, ht, dt, ib, it, ap, vo, sms = p[:15]
    vals = [code, q(name), q(short), counter, q(posted), systype, jv, lit(ht, True), lit(dt, True), ib, lit(it, False), q(ap), vo, q(sms)]
    sets = ', '.join('%s = EXCLUDED.%s' % (c.strip(), c.strip()) for c in cols.split(',')[1:])
    lines.append('INSERT INTO dbo.vochercategory (%s) VALUES (%s) ON CONFLICT (vochcatcode) DO UPDATE SET %s;' % (cols, ', '.join(vals), sets))
for line in open(sys.argv[2], encoding='utf-8', errors='replace'):
    p = [x.strip() for x in line.rstrip('\n').split('|')]
    if len(p) >= 3 and p[0] == 'D':
        lines.append('INSERT INTO dbo.vochercategorydetail (vochcatcode, subacccode) VALUES (%s, %s) ON CONFLICT DO NOTHING;' % (p[1], p[2]))
open(sys.argv[3], 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print('written', len(lines))
