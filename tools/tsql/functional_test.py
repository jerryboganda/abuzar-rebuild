"""Functional test of the translation mechanisms on a real PostgreSQL 17 (run in CI after ci_run.py).

Synthetic T-SQL objects over two throw-away tables are translated with the real translator, created, executed and their results asserted:
assignment SELECT semantics, cursors, result sets (refcursor protocol), identity, temp tables, dynamic SQL, INSERT ... EXEC, UPDATE ... FROM,
triggers with UPDATE(col), and the real translated table function udf_StringToTabl plus the dbo.tsql_* helpers.
usage: python tools/tsql/functional_test.py   (PG* environment variables select the database; db/pg/40_functions.sql must be applied)
"""
import os
import sys

import psycopg

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..'))

from tsql.parser import parse_object
from tsql.schema import Table, Col
from tsql.routines import Translator, Catalog

TABLES = {
    'zz_item': Table('zz_item', [Col('icode', 'integer', 'I', True, False), Col('name', 'citext', 'S', False, False),
                                 Col('qty', 'numeric(10,2)', 'N', False, False), Col('lastupdate', 'timestamp(3)', 'D')]),
    'zz_log': Table('zz_log', [Col('logid', 'integer', 'I', True, False), Col('msg', 'citext', 'S')]),
}
DDL = """
DROP TABLE IF EXISTS dbo.zz_item CASCADE; DROP TABLE IF EXISTS dbo.zz_log CASCADE;
CREATE TABLE dbo.zz_item (icode integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name citext NOT NULL, qty numeric(10,2) NOT NULL DEFAULT 0, lastupdate timestamp(3));
CREATE TABLE dbo.zz_log (logid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, msg citext);
"""

SRC = {
    'zz_assign': """CREATE PROCEDURE zz_assign @n VARCHAR(20), @q NUMERIC(10,2) OUTPUT AS
        SET @q = -1
        SELECT @q = qty FROM zz_item WHERE name = @n
        RETURN 7""",
    'zz_sum': """CREATE PROCEDURE zz_sum AS
        DECLARE @s NUMERIC(10,2), @v NUMERIC(10,2)
        DECLARE c CURSOR FOR SELECT qty FROM zz_item ORDER BY icode
        OPEN c
        FETCH NEXT FROM c INTO @v
        SET @s = 0
        WHILE @@FETCH_STATUS = 0
        BEGIN
            SET @s = @s + @v
            FETCH NEXT FROM c INTO @v
        END
        CLOSE c
        DEALLOCATE c
        SELECT total = @s""",
    'zz_ins': """CREATE PROCEDURE zz_ins @name VARCHAR(20) AS
        INSERT INTO zz_item (name, qty) VALUES (@name, 1)
        RETURN @@IDENTITY""",
    'zz_tmp': """CREATE PROCEDURE zz_tmp AS
        CREATE TABLE #t (a INT)
        INSERT #t VALUES (1)
        INSERT #t VALUES (2)
        SELECT n = COUNT(*) FROM #t""",
    'zz_dyn': """CREATE PROCEDURE zz_dyn @tbl VARCHAR(30) AS
        DECLARE @q VARCHAR(100)
        SET @q = 'select count(*) as n from ' + @tbl
        EXEC (@q)""",
    'zz_insexec': """CREATE PROCEDURE zz_insexec AS
        CREATE TABLE #r (n INT)
        INSERT #r EXEC zz_tmp
        SELECT total = SUM(n) FROM #r""",
    'zz_upd': """CREATE PROCEDURE zz_upd AS
        UPDATE zz_item SET qty = qty * 2 FROM zz_item i WHERE i.icode = 1
        RETURN @@ROWCOUNT""",
    'zz_str': """CREATE PROCEDURE zz_str @n INT, @s VARCHAR(40) OUTPUT AS
        SET @s = 'Item #' + LTRIM(RTRIM(STR(@n, 6))) + ' on ' + CONVERT(VARCHAR(10), CAST('2024-03-09' AS DATETIME), 103) + ' +' + CAST(DATEDIFF(day, '2024-03-01', '2024-03-09') AS VARCHAR(5))""",
}
TRIGGERS = {
    'zz_trg_upd': """CREATE TRIGGER zz_trg_upd ON zz_item AFTER UPDATE AS
        IF UPDATE(qty)
        BEGIN
            INSERT INTO zz_log (msg) SELECT 'q:' + CONVERT(VARCHAR(10), i.qty) FROM inserted i, deleted d WHERE i.icode = d.icode AND i.qty <> d.qty
        END""",
    'zz_trg_ins': """CREATE TRIGGER zz_trg_ins ON zz_item AFTER INSERT AS
        INSERT INTO zz_log (msg) SELECT 'new:' + name FROM inserted""",
}

fails = []


def check(desc, ok, detail=''):
    print(('ok    ' if ok else 'FAIL  ') + desc + ('' if ok else '   ' + str(detail)))
    if not ok:
        fails.append(desc)


def main():
    cat = Catalog()
    tr = Translator(TABLES, cat)
    nodes = {k: parse_object(v) for k, v in SRC.items()}
    tnodes = {k: parse_object(v) for k, v in TRIGGERS.items()}
    tr.build_catalog(list(nodes.values()))
    conn = psycopg.connect(autocommit=True)
    conn.execute('SET search_path TO dbo, public')
    conn.execute(DDL)
    for name, node in nodes.items():
        conn.execute(tr.translate_proc(node, SRC[name]))
    for name, node in tnodes.items():
        sql, _ = tr.translate_trigger(node, TRIGGERS[name])
        conn.execute(sql)

    def q1(sql, *a):
        return conn.execute(sql, a).fetchone()

    def fetch_rs(row, idx):
        # documented protocol: FETCH ALL, then CLOSE (an open cursor over a temp table blocks the next DROP/TRUNCATE of that table)
        rows = conn.execute('FETCH ALL FROM "%s"' % row[idx]).fetchall()
        conn.execute('CLOSE "%s"' % row[idx])
        return rows

    # ---- identity / insert / trigger on insert
    conn.execute('BEGIN')
    r = q1('SELECT return_value FROM dbo.zz_ins(%s)', 'bolt')
    check('RETURN @@IDENTITY gives the generated key', r[0] == 1, r)
    q1('SELECT return_value FROM dbo.zz_ins(%s)', 'nut')
    check('insert trigger saw the new row through the transition table',
          [x[0] for x in conn.execute("SELECT msg FROM dbo.zz_log ORDER BY logid").fetchall()] == ['new:bolt', 'new:nut'])
    # ---- assignment select semantics: last row wins, unchanged when no row
    conn.execute("UPDATE dbo.zz_item SET qty = 5 WHERE name = 'bolt'")
    row = q1('SELECT q, return_value FROM dbo.zz_assign(n => %s, q => %s)', 'bolt', 0)
    check('SELECT @q = col assigns the value', row[0] == 5 and row[1] == 7, row)
    row = q1('SELECT q, return_value FROM dbo.zz_assign(n => %s, q => %s)', 'missing', 0)
    check('SELECT @q = col with no row sets nothing (value from SET @q = -1 stays)', row[0] == -1, row)
    row = q1('SELECT q FROM dbo.zz_assign(n => %s, q => %s)', 'BOLT', 0)
    check('citext comparison is case-insensitive', row[0] == 5, row)
    # ---- trigger with UPDATE(qty)
    n0 = q1('SELECT count(*) FROM dbo.zz_log')[0]
    conn.execute("UPDATE dbo.zz_item SET name = 'nut2' WHERE name = 'nut'")
    n1 = q1('SELECT count(*) FROM dbo.zz_log')[0]
    check('UPDATE of another column does not run the UPDATE(qty) trigger', n1 == n0, (n0, n1))
    conn.execute("UPDATE dbo.zz_item SET qty = 9 WHERE name = 'nut2'")
    msgs = [x[0] for x in conn.execute("SELECT msg FROM dbo.zz_log ORDER BY logid").fetchall()]
    check('UPDATE of qty runs the trigger once with inserted/deleted', msgs[-1] == 'q:9.00' and len(msgs) == n0 + 1, msgs)
    conn.execute("UPDATE dbo.zz_item SET qty = qty WHERE name = 'nut2'")
    n2 = q1('SELECT count(*) FROM dbo.zz_log')[0]
    check('trigger body filtered out rows without a change', n2 == n0 + 1, n2)
    # ---- cursor + result set protocol
    row = q1('SELECT * FROM dbo.zz_sum()')
    rows = fetch_rs(row, 1)
    check('cursor loop + refcursor result set (5 + 9 = 14)', len(rows) == 1 and rows[0][0] == 14, rows)
    # ---- temp table, result set
    row = q1('SELECT * FROM dbo.zz_tmp()')
    check('temp table + COUNT result set', fetch_rs(row, 1)[0][0] == 2)
    row = q1('SELECT * FROM dbo.zz_tmp()')
    check('procedure can run twice in one transaction (temp table re-created)', fetch_rs(row, 1)[0][0] == 2)
    # ---- dynamic SQL
    row = q1('SELECT * FROM dbo.zz_dyn(%s)', 'dbo.zz_item')
    check('EXEC(@sql) SELECT returns a result set', fetch_rs(row, 1)[0][0] == 2)
    # ---- INSERT ... EXEC
    row = q1('SELECT * FROM dbo.zz_insexec()')
    check('INSERT #t EXEC proc copies the procedure result set', fetch_rs(row, 1)[0][0] == 2)
    # ---- UPDATE ... FROM
    row = q1('SELECT return_value FROM dbo.zz_upd()')
    qty1 = q1('SELECT qty FROM dbo.zz_item WHERE icode = 1')[0]
    check('UPDATE ... FROM updates only the matching row and @@ROWCOUNT is 1', row[0] == 1 and qty1 == 10, (row, qty1))
    # ---- string / date functions
    row = q1('SELECT s FROM dbo.zz_str(n => %s, s => %s)', 42, '')
    check('STR/LTRIM/CONVERT 103/CAST/DATEDIFF', row[0] == 'Item #42 on 09/03/2024 +8', row)
    # ---- real translated table function + helpers
    rows = conn.execute("SELECT code FROM dbo.udf_stringtotabl(%s, %s) ORDER BY code", ('3,1,2,2', ',')).fetchall()
    check('udf_StringToTabl splits and de-duplicates', [x[0] for x in rows] == [1, 2, 3], rows)
    check('dbo.tsql_str', q1("SELECT dbo.tsql_str(12.5, 8, 2)")[0] == '   12.50')
    # STR results measured on SQL Server 2022 (constants only): float rounding, shrinking decimals, signed zero, limits
    str_cases = [
        ('2.675', 12, 2, '        2.67'), ('1.005', 12, 2, '        1.00'), ('0.125', 12, 2, '        0.13'),
        ('1234.565', 12, 2, '     1234.57'), ('1234.565', 6, 2, '1234.6'), ('1234.565', 5, 2, ' 1235'),
        ('-2.675', 12, 2, '       -2.67'), ('10.0049999', 10, 4, '   10.0050'), ('123456.785', 6, 2, '123457'),
        ('123456.785', 5, 2, '*****'), ('99999.995', 12, 2, '    99999.99'), ('99999.995', 6, 2, '100000'),
        ('-0.4', 10, 0, '        -0'), ('-0.001', 12, 2, '       -0.00'), ('1.00005', 10, 4, '    1.0001'),
        ('12345678.9', 10, 4, '12345678.9'), ('9.96', 3, 1, '***'), ('9.96', 4, 1, '10.0'), ('99.5', 2, 0, '**'),
        ('-9.96', 4, 1, '****'), ('0.5', 10, 0, '         1'), ('-0.5', 10, 0, '        -1'), ('2.5', 10, 0, '         3'),
        ('1e16', 20, 0, '   10000000000000000'), ('12.3456', 20, 18, ' 12.3455999999999990'),
        ('0.1', 20, 17, '  0.1000000000000000'), ('-1234.565', 6, 2, ' -1235'), ('0.9996', 4, 3, '1.00'),
        ('999.96', 5, 2, '*****'), ('-123.4', 3, 0, '***'), ('1.45', 10, 1, '       1.5'), ('0.285', 10, 2, '      0.28'),
        ('1.115', 10, 2, '      1.12'), ('0.105', 20, 2, '                0.11'), ('-0.04', 4, 1, '-0.0'),
        ('123456789012345678', 20, 0, '  123456789012345680'), ('0.000001234', 20, 16, '  0.0000012340000000'),
        ('1.5', 0, 0, None), ('1.5', 10, -1, None), ('1.5', 8001, 0, None),
    ]
    for n, ln, d, want in str_cases:
        got = q1('SELECT dbo.tsql_str(%s::numeric, %s, %s)', n, ln, d)[0]
        check('STR(%s, %d, %d) = %r as on SQL Server' % (n, ln, d, want), got == want, got)
    # CONVERT(varchar, datetime, style) measured on SQL Server 2022: blank-padded day and hour, 126 without .000
    convert_cases = [
        ('2024-01-09 15:05:07.123', 0, 'Jan  9 2024  3:05PM'), ('2024-01-09 15:05:07.123', 9, 'Jan  9 2024  3:05:07:123PM'),
        ('2024-11-23 00:00:00', 100, 'Nov 23 2024 12:00AM'), ('2024-11-23 00:00:00', 109, 'Nov 23 2024 12:00:00:000AM'),
        ('2024-11-23 00:00:00', 126, '2024-11-23T00:00:00'), ('2024-02-29 12:30:00.997', 0, 'Feb 29 2024 12:30PM'),
        ('2024-02-29 12:30:00.997', 126, '2024-02-29T12:30:00.997'), ('2024-12-01 09:00:59.003', 0, 'Dec  1 2024  9:00AM'),
        ('2024-12-01 09:00:59.003', 9, 'Dec  1 2024  9:00:59:003AM'),
    ]
    for ts, style, want in convert_cases:
        got = q1('SELECT dbo.tsql_convert_dt(%s::timestamp, %s)', ts, style)[0]
        check('CONVERT(varchar, %s, %d) = %r as on SQL Server' % (ts, style, want), got == want, got)
    # ORDER BY of character data under SQL_Latin1_General_CP1_CI_AS, measured on SQL Server 2022 (ties by binary order)
    ascii_order = ' !"#$%&\'()*+,-./:;<=>?@[\\]^_`{|}~0123456789' + ''.join(c + c.lower() for c in 'ABCDEFGHIJKLMNOPQRSTUVWXYZ')
    got = q1("SELECT string_agg(ch, '' ORDER BY (ch || 'x')::citext COLLATE dbo.sqlserver_ci, ascii(ch)) "
             "FROM (SELECT chr(c) AS ch FROM generate_series(32, 126) AS c) AS s")[0]
    check('printable ASCII sorts as on SQL Server (blank, punctuation, digits, letters)', got == ascii_order, got)
    name_order = [' X', '-X', '1-A', '10', '9', 'A&B', 'A+B', 'A/B', 'A_B', 'A~', 'A1', 'A9', 'AB', 'CO OP', 'CO-OP', 'COOP',
                  'ECOLE', 'ÉCOLE', 'EDGE', "O'NEIL", 'ONEIL', 'PANADOL', 'panadol', 'PANADOL 10S', 'PANADOL CF',
                  'PANADOL EXTRA', 'PANADOL(500MG)', 'Panadol-cf', 'PANADOL-EXTRA', 'PANADOL.SYP', 'PANADOL10S', 'PANADOLEXTRA',
                  'X', 'Zz', 'zZ']
    rows = conn.execute('SELECT s FROM unnest(%s::text[]) AS s ORDER BY s::citext COLLATE dbo.sqlserver_ci, s COLLATE "C"',
                        (sorted(name_order, reverse=True),)).fetchall()
    got = [r[0] for r in rows]
    check('item-like names sort as on SQL Server', got == name_order, got)
    check('application citext columns use the SQL Server order',
          q1("SELECT count(*) FROM pg_attribute a JOIN pg_class t ON t.oid = a.attrelid JOIN pg_namespace n ON n.oid = t.relnamespace "
             "WHERE n.nspname = 'dbo' AND t.relkind = 'r' AND left(t.relname, 3) <> 'zz_' AND a.attnum > 0 AND a.atttypid = 'citext'::regtype "
             "AND a.attcollation <> (SELECT oid FROM pg_collation WHERE collname = 'sqlserver_ci')")[0] == 0)
    check('dbo.tsql_datediff month', q1("SELECT dbo.tsql_datediff('month', timestamp '2024-01-31', timestamp '2024-03-01')")[0] == 2)
    check('dbo.tsql_charindex with start', q1("SELECT dbo.tsql_charindex('b', 'abcabc', 3)")[0] == 5)
    check('dbo.tsql_dyn normalises DELETE x', q1("SELECT dbo.tsql_dyn('DELETE zz_item WHERE 1=0')")[0] == 'DELETE FROM zz_item WHERE 1=0')
    conn.execute('ROLLBACK')
    conn.execute('DROP TABLE IF EXISTS dbo.zz_item CASCADE; DROP TABLE IF EXISTS dbo.zz_log CASCADE;')
    for name in list(SRC) + ['trg_zz_trg_upd', 'trg_zz_trg_ins']:
        conn.execute("DO $$ DECLARE r record; BEGIN FOR r IN SELECT p.oid::regprocedure AS f FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace "
                     "WHERE n.nspname = 'dbo' AND p.proname = '%s' LOOP EXECUTE 'DROP FUNCTION ' || r.f || ' CASCADE'; END LOOP; END $$" % name.lower())
    print('%d failed' % len(fails))
    sys.exit(1 if fails else 0)


if __name__ == '__main__':
    main()
