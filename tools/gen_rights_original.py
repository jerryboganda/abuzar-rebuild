"""Generate db/pg/91_rights_original.sql: the rights of the original with the codes the scripts check.

The scripts call f_rightexists(<code>) with the codes of the original's `Rights` table (4 = Purchase Order, 10 = Cash Sale, 11 = Credit Sale, 81 = Item ...); the migration chain of the original
(90_seed.sql) only defines part of them and the menu rights generated by 92_menu_rights.sql get new codes, so on a fresh database those checks failed and windows hid what the
original shows (the tabs of Interface Settings, buttons of the entry windows).  Only the definition of the rights is exported - no group, user or customer data.

usage (local only):
  sqlcmd -S .\\SQLEXPRESS2022 -E -C -d <db> -W -h -1 -s "|" -Q "SET NOCOUNT ON; SELECT rightcode, rightname, ISNULL(menuname,'NULL'), levelindex, indicesstring, object, rightcatcode FROM dbo.Rights ORDER BY rightcode" > rights.txt
  python -I tools/gen_rights_original.py rights.txt db/pg/91_rights_original.sql
"""
import sys


def q(s):
    return "'" + s.replace("'", "''") + "'"


rows = []
for line in open(sys.argv[1], encoding='utf-8', errors='replace'):
    p = [x.strip() for x in line.rstrip('\n').split('|')]
    if len(p) >= 7 and p[0].isdigit():
        rows.append(p)
out = [
    '-- Generated by tools/gen_rights_original.py from the Rights table of the compared deployment of the original: the definition of every right with its original code',
    '-- (f_rightexists(10) = Cash Sale ...).  Applied after the seed and before 92_menu_rights.sql, which then only adds menu positions no right names yet.  Idempotent.',
    '',
]
for code, name, menu, level, indices, obj, cat in rows:
    out.append(
        'INSERT INTO dbo.rights (rightcode, rightname, menuname, levelindex, indicesstring, object, rightcatcode) VALUES (%s, %s, %s, %s, %s, %s, %s) '
        'ON CONFLICT (rightcode) DO UPDATE SET rightname = EXCLUDED.rightname, menuname = EXCLUDED.menuname, levelindex = EXCLUDED.levelindex, indicesstring = EXCLUDED.indicesstring, '
        'object = EXCLUDED.object, rightcatcode = EXCLUDED.rightcatcode;'
        % (code, q(name), 'NULL' if menu == 'NULL' else q(menu), level, q(indices), q(obj), cat))
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('rights', len(rows))
