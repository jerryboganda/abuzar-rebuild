"""Generate db/pg/93_chart_base.sql: the chart-of-accounts base of the compared deployment of the original.

A new company database of the original starts with the main accounts, their categories, the sub accounts and the built-in system accounts (cash, sales,
purchase, inventory, taxes ... and the retail sale customer 19) plus the `Global` table that tells the program which account plays which role.
Only that structure is exported - never the accounts of customers, suppliers or users: the account list is cut to the codes that `Global` names.

usage (local only):
  sqlcmd -S .\\SQLEXPRESS2022 -E -C -d <db> -W -h -1 -s "|" -Q "SET NOCOUNT ON; SELECT 'M', mainacccode, name FROM MainAccounts" > main.txt
  ... "SELECT 'C', catacccode, mainacccode, name FROM CategoryAccounts WHERE catacccode BETWEEN 1 AND 11" > cat.txt
  ... "SELECT 'S', subacccode, catacccode, name FROM SubAccounts ORDER BY 2" > sub.txt
  ... "SELECT 'A', acccode, subcode, name, aliasname, active, restricted, alertcode FROM Accounts WHERE acccode IN (SELECT code FROM Global WHERE tablename='Accounts') ORDER BY acccode" > acc.txt
  ... "SELECT 'G', name, tablename, code, description FROM Global ORDER BY name" > glob.txt
  python -I tools/gen_chart_base.py main.txt cat.txt sub.txt acc.txt glob.txt db/pg/93_chart_base.sql
"""
import sys


def rows(path, tag, n):
    out = []
    for line in open(path, encoding='utf-8', errors='replace'):
        p = [x.strip() for x in line.rstrip('\n').split('|')]
        if p and p[0] == tag and len(p) >= n:
            out.append(p[1:n] + (p[n:] if len(p) > n else []))
    return out


def q(s):
    return "'" + s.replace("'", "''") + "'"


main, cat, sub, acc, glob = (sys.argv[i] for i in range(1, 6))
out_path = sys.argv[6]
lines = [
    '-- Generated by tools/gen_chart_base.py from the configuration of the compared deployment of the original: the chart-of-accounts base, the built-in system',
    '-- accounts and the Global role table.  No customer / supplier / user accounts.  Idempotent; applied before 94_deployment_profile.sql and 95_bootstrap.sql.',
    '',
]
for code, name in rows(main, 'M', 3):
    lines.append('INSERT INTO dbo.mainaccounts (mainacccode, name) VALUES (%s, %s) ON CONFLICT DO NOTHING;' % (code, q(name)))
for code, main_code, name in rows(cat, 'C', 4):
    lines.append('INSERT INTO dbo.categoryaccounts (catacccode, mainacccode, name) VALUES (%s, %s, %s) ON CONFLICT DO NOTHING;' % (code, main_code, q(name)))
for code, cat_code, name in rows(sub, 'S', 4):
    lines.append('INSERT INTO dbo.subaccounts (subacccode, catacccode, name) VALUES (%s, %s, %s) ON CONFLICT DO NOTHING;' % (code, cat_code, q(name)))
for r in rows(acc, 'A', 8):
    code, subcode, name, alias, active, restricted, alert = r[:7]
    lines.append(
        'INSERT INTO dbo.accounts (acccode, subcode, name, aliasname, active, restricted, alertcode) VALUES (%s, %s, %s, %s, %s, %s, %s) ON CONFLICT DO NOTHING;'
        % (code, subcode, q(name), q(alias) if alias and alias != 'NULL' else 'NULL', q(active), q(restricted), alert))
for r in rows(glob, 'G', 4):
    name, table, code = r[0], r[1], r[2]
    desc = r[3] if len(r) > 3 and r[3] != 'NULL' else ''
    lines.append(
        'INSERT INTO dbo.global (name, tablename, code, description) VALUES (%s, %s, %s, %s) ON CONFLICT (name) DO UPDATE SET tablename = EXCLUDED.tablename, code = EXCLUDED.code;'
        % (q(name), q(table), code, q(desc) if desc else 'NULL'))
open(out_path, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print('written', len(lines))
