// Generates explicit compatibility surfaces for on-screen DataWindows whose source structure has no Modern mapping yet.
// A compatibility surface keeps the original Classic DataWindow rendering inside the Modern frame; it is not a Modern
// field layout and is reported separately by the completion audit.
//
// usage: node tools/derive-compatibility-data-surfaces.ts [--check]     (run from web/)
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve } from 'node:path'
import type { DataSurface } from '../src/ui/data-surfaces.ts'
import { loadDefinitions } from './derive-data-surfaces.ts'
import { COMPATIBILITY_REASONS } from './compatibility-data.ts'

const here = import.meta.dirname
export const OUTPUT_TS = resolve(here, '..', 'src', 'ui', 'derived-compatibility-data-surfaces.ts')
export const OUTPUT_BACKLOG = resolve(here, '..', '..', 'docs', 'ui-derived-compatibility-data-surfaces-backlog.json')

const titleOf = (name: string) => name.replace(/^d_/, '').split('_').filter(Boolean)
  .map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join(' ')

export function deriveCompatibilitySurfaces() {
  const definitions = loadDefinitions()
  const surfaces: DataSurface[] = []
  const missing: string[] = []
  for (const name of Object.keys(COMPATIBILITY_REASONS).sort()) {
    if (!definitions.has(name)) { missing.push(name); continue }
    surfaces.push({ name, title: titleOf(name), kind: 'form', compatibility: true, fields: [] })
  }
  return { surfaces, missing, total: Object.keys(COMPATIBILITY_REASONS).length }
}

export function render(surfaces: readonly DataSurface[]): string {
  return [
    '// GENERATED by web/tools/derive-compatibility-data-surfaces.ts. Do not edit; regenerate instead.',
    '// Compatibility surfaces keep the original Classic rendering; they are not Modern field layouts.',
    "import type { DataSurface } from './data-surfaces.ts'",
    '',
    'export const DERIVED_COMPATIBILITY_DATA_SURFACES: readonly DataSurface[] = [',
    ...surfaces.map((surface) => `  ${JSON.stringify(surface)},`),
    ']',
    '',
  ].join('\n')
}

export function renderBacklog(surfaces: readonly DataSurface[], missing: readonly string[]): string {
  return JSON.stringify({
    note: 'Generated by web/tools/derive-compatibility-data-surfaces.ts. Compatibility surfaces retain the original Classic DataWindow rendering and are not counted as Modern field layouts.',
    definitions: COMPATIBILITY_REASONS,
    derived: surfaces.length,
    missing,
  }, null, 1) + '\n'
}

if (import.meta.main) {
  const outcome = deriveCompatibilitySurfaces()
  if (outcome.missing.length) {
    console.error(`Missing compatibility definitions: ${outcome.missing.join(', ')}`)
    process.exit(1)
  }
  const ts = render(outcome.surfaces), json = renderBacklog(outcome.surfaces, outcome.missing)
  if (process.argv.includes('--check')) {
    const stale = !existsSync(OUTPUT_TS) || readFileSync(OUTPUT_TS, 'utf8') !== ts ||
      !existsSync(OUTPUT_BACKLOG) || readFileSync(OUTPUT_BACKLOG, 'utf8') !== json
    if (stale) { console.error('Compatibility surfaces are stale; run node tools/derive-compatibility-data-surfaces.ts'); process.exit(1) }
  } else {
    writeFileSync(OUTPUT_TS, ts)
    writeFileSync(OUTPUT_BACKLOG, json)
  }
  console.log(`compatibility surfaces ${outcome.surfaces.length}`)
}
