// Rights profile of the deployment the rebuild is compared with: the original showed ADMIN a subset of the main menu (m_entry); docs/observed/
// original-menu-frame.tsv is its live menu tree (read from the running abuzar.exe with tools/orig/crawl.ps1 dump).  This maps every observed item to its
// position in m_entry and writes db/pg/96_rights_profile.sql, which removes the group rights of every other menu item.
// usage: node tools/gen-profile.ts <public/data dir> <observed.tsv> <out sql>
import { readFileSync, existsSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { gunzipSync } from 'node:zlib'
import { createRuntime } from '../src/runtime/boot.ts'
import { JsonClassLoader } from '../src/runtime/loader.ts'
import type { PBObject } from '../src/runtime/object.ts'

const [dataDir, observed, out] = process.argv.slice(2)
const read = async (p: string): Promise<string | undefined> => {
  const f = join(dataDir, p)
  if (existsSync(f)) return readFileSync(f, 'utf8')
  if (existsSync(f + '.gz')) return gunzipSync(readFileSync(f + '.gz')).toString('utf8')
  return undefined
}
const names = JSON.parse((await read('names.json')) || '{}')
const loader = new JsonClassLoader((n) => read(`classes/${n}.json`))
const rt = await createRuntime({ loader, readData: read, sharedVars: names.sharedVars, globalTypes: names.globalTypes, ui: { async messageBox() { return 1 } } as never })
rt.onError = () => {}
const menu = (await rt.instantiate('m_entry', null)) as PBObject

const clean = (s: unknown): string => String(s ?? '').replace(/<TAB>/g, ' ').replace(/&/g, '').replace(/\s+/g, ' ').trim()

interface Obs { text: string; kids: Obs[] }
const root: Obs = { text: '', kids: [] }
for (const line of readFileSync(observed, 'utf8').replace(/^﻿/, '').split(/\r?\n/)) {
  const p = line.split('\t')
  if (p.length < 4 || p[1] === 'sep') continue
  const parts = p[3].split(' | ').map(clean)
  let n = root
  for (const part of parts.slice(0, -1)) n = n.kids.find((k) => k.text === part) ?? n
  n.kids.push({ text: parts[parts.length - 1], kids: [] })
}

const picked: string[] = []
const missing: string[] = []
const walk = (m: PBObject, o: Obs, idx: number[], path: string[]) => {
  const items = [...m.children.values()]
  let j = 0
  for (const k of o.kids) {
    let found = -1
    const t = (i: number) => clean(items[i].props.get('text')).toLowerCase()
    for (let i = j; i < items.length; i++) if (t(i) === k.text.toLowerCase()) { found = i; break }
    // the program renames a few items at run time (e.g. drops a suffix such as "(One Category)")
    if (found < 0) for (let i = j; i < items.length; i++) if (t(i).startsWith(k.text.toLowerCase())) { found = i; break }
    if (found < 0) { missing.push([...path, k.text].join(' > ')); continue }
    j = found + 1
    const ix = [...idx, found + 1]
    picked.push(ix.join(',') + ',')
    walk(items[found], k, ix, [...path, k.text])
  }
}
walk(menu, root, [], [])

const list = picked.map((s) => `'${s}'`).join(', ')
writeFileSync(
  out,
  `-- Rights profile of the compared deployment (FazalDin PP19): the original showed ADMIN ${picked.length} menu items, not all ${1460}.
-- Generated by web/tools/gen-profile.ts from docs/observed/original-menu-frame.tsv.  Remove this script (or re-grant with 95_bootstrap.sql)
-- to give the groups every right of the main menu.
DELETE FROM dbo.grouprights gr USING dbo.rights r
 WHERE gr.rightcode = r.rightcode AND r.object = 'A' AND r.indicesstring ~ '^[0-9]+(,[0-9]+)*,$'
   AND r.indicesstring NOT IN (${list});
`,
)
console.log(`observed items ${picked.length + missing.length}, matched ${picked.length}, unmatched ${missing.length}`)
if (missing.length) console.log('unmatched:', missing.slice(0, 40))
setTimeout(() => process.exit(0), 100)
