// Derives Modern surfaces for entry-hosted DataWindows that have no reviewed or contextual mapping.  These are the
// on-screen lookup/detail grids and masters whose host entry window keeps them hidden, passive or runtime-assigned.
// Every surface passes `dataSurfaceIssues` and `dataSurfacePositionIssues` before it is written.
//
// usage: node tools/derive-screen-data-surfaces.ts [--check]     (run from web/)
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve } from 'node:path'
import { deriveValidated, entryHostedDataWindows, loadDefinitions } from './derive-data-surfaces.ts'
import type { DataSurface } from '../src/ui/data-surfaces.ts'
import { DATA_SURFACES } from '../src/ui/data-surfaces.ts'
import { DERIVED_DATA_SURFACES } from '../src/ui/derived-data-surfaces.ts'
import {
  WINDOW_SURFACES, CRITERIA_WINDOW_SURFACES, CALCULATOR_WINDOW_SURFACES, CALENDAR_WINDOW_SURFACES, ENTRY_WINDOW_SURFACES,
} from '../src/ui/window-surfaces.ts'
import { DERIVED_ENTRY_WINDOW_SURFACES } from '../src/ui/derived-entry-windows.ts'
import { DERIVED_MODAL_WINDOW_SURFACES } from '../src/ui/derived-modal-windows.ts'

const here = import.meta.dirname
export const OUTPUT_TS = resolve(here, '..', 'src', 'ui', 'derived-screen-data-surfaces.ts')
export const OUTPUT_BACKLOG = resolve(here, '..', '..', 'docs', 'ui-derived-screen-data-surfaces-backlog.json')
const classificationPath = resolve(here, '..', '..', 'docs', 'ui-print-classification.json')

export function deriveScreenDataSurfaces() {
  const definitions = loadDefinitions()
  const covered = new Set<string>()
  for (const surface of [...DATA_SURFACES, ...DERIVED_DATA_SURFACES]) covered.add(surface.name)
  for (const entry of ENTRY_WINDOW_SURFACES) {
    for (const detail of entry.details) if (detail.surface) covered.add(detail.surface.name)
    if (entry.list) covered.add(entry.list.name)
  }
  for (const window of [...WINDOW_SURFACES, ...CRITERIA_WINDOW_SURFACES, ...CALCULATOR_WINDOW_SURFACES, ...CALENDAR_WINDOW_SURFACES]) {
    for (const binding of window.data ?? []) covered.add(binding.surface.name)
  }
  for (const entry of DERIVED_ENTRY_WINDOW_SURFACES) {
    for (const detail of entry.details) if (detail.surface) covered.add(detail.surface.name)
    if (entry.list) covered.add(entry.list.name)
  }
  for (const window of DERIVED_MODAL_WINDOW_SURFACES) for (const binding of window.data ?? []) covered.add(binding.surface.name)
  // Print, PDF and report output is redesigned separately; these entry-hosted documents keep their own presentation.
  const classification = existsSync(classificationPath) ? JSON.parse(readFileSync(classificationPath, 'utf8')) : null
  const exempt = new Set<string>(['report-or-document', 'print-target', 'registered-template']
    .flatMap((key) => classification?.members?.[key] ?? []))
  const surfaces: DataSurface[] = []
  const backlog: Record<string, string[]> = {}
  for (const name of [...entryHostedDataWindows()].sort()) {
    if (covered.has(name) || exempt.has(name)) continue
    const definition = definitions.get(name)
    if (!definition) {
      ;(backlog['missing definition'] ??= []).push(name)
      continue
    }
    const outcome = deriveValidated(name, definition)
    if (outcome.surface) surfaces.push(outcome.surface)
    else (backlog[outcome.reason!] ??= []).push(name)
  }
  return { surfaces, backlog, total: entryHostedDataWindows().size, covered: covered.size, exempt: exempt.size }
}

export function render(surfaces: readonly DataSurface[]): string {
  return [
    '// GENERATED by web/tools/derive-screen-data-surfaces.ts from data/src/dw. Do not edit; regenerate instead.',
    '// Entry-hosted on-screen DataWindows that had no reviewed or contextual mapping; each entry passes dataSurfaceIssues.',
    "import type { DataSurface } from './data-surfaces.ts'",
    '',
    'export const DERIVED_SCREEN_DATA_SURFACES: readonly DataSurface[] = [',
    ...surfaces.map((surface) => `  ${JSON.stringify(surface)},`),
    ']',
    '',
  ].join('\n')
}

export function renderBacklog(total: number, derived: number, backlog: Record<string, string[]>): string {
  const reasons = Object.entries(backlog).sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]))
  return JSON.stringify({
    note: 'Generated by web/tools/derive-screen-data-surfaces.ts. Listed entry-hosted on-screen DataWindows keep their original element until a reviewed mapping exists.',
    entryHosted: total,
    derived: derived,
    pending: reasons.reduce((sum, [, names]) => sum + names.length, 0),
    reasons: Object.fromEntries(reasons.map(([reason, names]) => [reason, { count: names.length, names }])),
  }, null, 1) + '\n'
}

if (import.meta.main) {
  const outcome = deriveScreenDataSurfaces()
  const ts = render(outcome.surfaces), json = renderBacklog(outcome.total, outcome.surfaces.length, outcome.backlog)
  if (process.argv.includes('--check')) {
    const stale = !existsSync(OUTPUT_TS) || readFileSync(OUTPUT_TS, 'utf8') !== ts ||
      !existsSync(OUTPUT_BACKLOG) || readFileSync(OUTPUT_BACKLOG, 'utf8') !== json
    if (stale) { console.error('Derived screen DataWindow surfaces are stale; run node tools/derive-screen-data-surfaces.ts'); process.exit(1) }
  } else {
    writeFileSync(OUTPUT_TS, ts)
    writeFileSync(OUTPUT_BACKLOG, json)
  }
  console.log(`entry-hosted ${outcome.total}; covered ${outcome.covered}; exempt ${outcome.exempt}; derived ${outcome.surfaces.length}; pending ${Object.values(outcome.backlog).reduce((sum, names) => sum + names.length, 0)}`)
  for (const [reason, names] of Object.entries(outcome.backlog).sort((a, b) => b[1].length - a[1].length).slice(0, 15)) console.log(`  ${names.length}\t${reason}`)
}
