-- Audit trail (enhancement; the original application recorded nothing about who changed master data).
-- Every insert / update / delete of a watched table is written to dbo.audit_log with the old and the new row and the application
-- user.  The UI sets the user per session with  SET app.user = '<user code>'  after login; without it the column stays empty.
-- Password columns are never copied into the log.

CREATE TABLE IF NOT EXISTS dbo.audit_log (
    audit_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    at timestamp(3) NOT NULL DEFAULT localtimestamp(3),
    db_user text NOT NULL DEFAULT current_user,
    app_user text NULL,
    table_name text NOT NULL,
    operation char(1) NOT NULL,
    old_row jsonb NULL,
    new_row jsonb NULL,
    CONSTRAINT pk_audit_log PRIMARY KEY (audit_id)
);
CREATE INDEX IF NOT EXISTS audit_log_table_at ON dbo.audit_log (table_name, at);

CREATE OR REPLACE FUNCTION dbo.audit_trigger() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO dbo.audit_log (app_user, table_name, operation, old_row, new_row)
    VALUES (nullif(current_setting('app.user', true), ''), TG_TABLE_NAME, left(TG_OP, 1),
            CASE WHEN TG_OP IN ('UPDATE', 'DELETE') THEN to_jsonb(OLD) - 'password' END,
            CASE WHEN TG_OP IN ('UPDATE', 'INSERT') THEN to_jsonb(NEW) - 'password' END);
    RETURN NULL;
END
$$;

-- watch a table: SELECT dbo.enable_audit('item');
CREATE OR REPLACE FUNCTION dbo.enable_audit(tbl text) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    EXECUTE format('DROP TRIGGER IF EXISTS audit_trail ON dbo.%I', tbl);
    EXECUTE format('CREATE TRIGGER audit_trail AFTER INSERT OR UPDATE OR DELETE ON dbo.%I FOR EACH ROW EXECUTE FUNCTION dbo.audit_trigger()', tbl);
END
$$;

SELECT dbo.enable_audit(t)
FROM unnest(ARRAY['users', 'usergroups', 'userrights', 'grouprights', 'rights', 'preferences', 'accounts', 'customer', 'supplier', 'item']) AS t;
