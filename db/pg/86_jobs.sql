-- SQL Server Agent stand-in: the application asks `SysJobs` whether its scheduled jobs (backup, posting, CRS sending ...) are enabled, and `SysJobSchedules` for the repeating schedule of each job.
--
-- PostgreSQL has no Agent: the tables below keep the same information the SQL Agent tables provide, and the two `sp_...` procedures below replace `msdb..sp_update_job` / `msdb..sp_update_jobschedule` with plain PostgreSQL writes (the schedule itself is run by the operating system's task scheduler).
CREATE TABLE IF NOT EXISTS dbo.sysjobs (
  name citext COLLATE dbo.sqlserver_ci PRIMARY KEY,
  enabled smallint NOT NULL DEFAULT 0
);

-- installations created before `job_id` existed: add it and make it unique so schedules can reference it
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'dbo' AND table_name = 'sysjobs' AND column_name = 'job_id'
  ) THEN
    ALTER TABLE dbo.sysjobs ADD COLUMN job_id integer GENERATED BY DEFAULT AS IDENTITY;
    ALTER TABLE dbo.sysjobs ADD CONSTRAINT sysjobs_job_id_key UNIQUE (job_id);
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS dbo.sysjobschedules (
  schedule_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id integer NOT NULL REFERENCES dbo.sysjobs (job_id) ON DELETE CASCADE,
  name citext COLLATE dbo.sqlserver_ci NOT NULL,
  freq_subday_type integer NOT NULL DEFAULT 1,
  freq_subday_interval integer NOT NULL DEFAULT 0,
  active_start_time bigint NOT NULL DEFAULT 0,
  UNIQUE (job_id, name)
);

-- sp_AdjustJobSchedule: update the job's schedule and leave it disabled until sp_ActivateJob enables it
CREATE OR REPLACE FUNCTION dbo.sp_adjustjobschedule(
  jobname citext, schedulename citext, starttime bigint, unit integer, unitvalue integer,
  OUT return_value integer
) RETURNS integer LANGUAGE plpgsql AS $$
DECLARE
  v_job_id integer;
BEGIN
  -- The recovered application globals for the SQL Agent job names are empty in
  -- this deployment (the original main database has no SysJobs/SysJobSchedules
  -- at all), and the open handlers call this procedure for every tab.  Do not
  -- create an empty-name job row from an unconfigured screen.
  IF jobname IS NULL OR btrim(jobname::text) = '' THEN
    return_value := 0;
    RETURN;
  END IF;

  INSERT INTO dbo.sysjobs (name, enabled) VALUES (jobname, 0)
    ON CONFLICT (name) DO UPDATE SET enabled = 0
    RETURNING job_id INTO v_job_id;

  IF schedulename IS NOT NULL AND btrim(schedulename::text) <> '' THEN
    INSERT INTO dbo.sysjobschedules (job_id, name, freq_subday_type, freq_subday_interval, active_start_time)
      VALUES (v_job_id, schedulename, unit, unitvalue, starttime)
      ON CONFLICT (job_id, name) DO UPDATE SET
        freq_subday_type = EXCLUDED.freq_subday_type,
        freq_subday_interval = EXCLUDED.freq_subday_interval,
        active_start_time = EXCLUDED.active_start_time;
  END IF;

  return_value := 0;
  RETURN;
END $$;

-- sp_ActivateJob: enable / disable a job (msdb..sp_update_job @enabled)
CREATE OR REPLACE FUNCTION dbo.sp_activatejob(
  jobname citext, activate integer,
  OUT return_value integer
) RETURNS integer LANGUAGE plpgsql AS $$
BEGIN
  IF jobname IS NULL OR btrim(jobname::text) = '' THEN
    return_value := 0;
    RETURN;
  END IF;

  INSERT INTO dbo.sysjobs (name, enabled) VALUES (jobname, activate::smallint)
    ON CONFLICT (name) DO UPDATE SET enabled = EXCLUDED.enabled;

  return_value := 0;
  RETURN;
END $$;
